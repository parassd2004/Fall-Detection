def send_otp_email(to: str, otp: str, purpose: str = "verification") -> bool:
    """Send OTP for registration or password reset."""
    subject = f"Your OTP Code — IoT Fall Detection"
    plain   = f"Your OTP for {purpose} is: {otp}\nValid for 2 minutes."
    html    = _otp_html(otp, purpose)
    return _send(to, subject, html, plain)


def send_fall_alert_email(to: str, acc: float, gyro: float) -> bool:
    """Send fall detection alert to caregiver."""
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    subject   = "⚠️ FALL ALERT — Patient Needs Attention"
    plain     = (
        f"FALL DETECTED\n"
        f"Time: {timestamp}\n"
        f"Acceleration: {acc:.2f} g\n"
        f"Gyroscope: {gyro:.2f} °/s\n\n"
        f"Please check on the patient immediately."
    )
    html = _fall_alert_html(acc, gyro, timestamp)
    return _send(to, subject, html, plain)
