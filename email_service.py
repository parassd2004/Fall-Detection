# ── Core send function ───────────────────────────────────────
def _send(to: str, subject: str, html_body: str, plain_body: str = "") -> bool:
    """
    Internal send function.
    Returns True on success, False on failure.
    Never raises — caller checks return value.
    """
    if not APP_PASSWORD:
        print("[EMAIL] ERROR: GMAIL_APP_PASSWORD environment variable not set.")
        return False

    try:
        msg = MIMEMultipart("alternative")
        msg["Subject"] = subject
        msg["From"]    = f"IoT Fall Detection <{SENDER_EMAIL}>"
        msg["To"]      = to

        # Plain text fallback
        if plain_body:
            msg.attach(MIMEText(plain_body, "plain"))

        # HTML version (preferred by email clients)
        msg.attach(MIMEText(html_body, "html"))

        with smtplib.SMTP("smtp.gmail.com", 587, timeout=10) as server:
            server.ehlo()
            server.starttls()
            server.login(SENDER_EMAIL, APP_PASSWORD)
            server.send_message(msg)

        print(f"[EMAIL] ✓ Sent to {to} | Subject: {subject}")
        return True

    except smtplib.SMTPAuthenticationError:
        print("[EMAIL] ERROR: Gmail authentication failed. Check APP_PASSWORD.")
        return False
    except smtplib.SMTPException as e:
        print(f"[EMAIL] SMTP error: {e}")
        return False
    except Exception as e:
        print(f"[EMAIL] Unexpected error: {e}")
        return False


